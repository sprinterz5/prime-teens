"""Генерирует seed/template.xlsx — шаблон для /template и Excel-импорта:
python -m tools.make_template

Один лист, блоки групп друг под другом — формат разбирает
app/roster_sheet.py (см. его докстринг за полным описанием). Каждый блок:

  1) строка-заголовок группы — где-то в ней название, где-то смена
     («Утренняя»/«Вечерняя»), где-то дата старта, где-то формат
     («Оффлайн»/«Онлайн») — позиции не фиксированы, парсер ищет по смыслу;
  2) строка с названиями колонок: Ментор | Номер телефона | # | Ученик |
     Контакты | Школа | Класс;
  3) строки учеников — «Ментор»/«Номер телефона» заполнены только в первой
     строке блока (дальше протягиваются вниз, forward-fill).

Блоки «Шаблон» и «Пример» — демонстрационные, их bot НЕ импортирует: всё,
что нужно реально загрузить, идёт НИЖЕ строки-маркера «Настоящие группы
отсюда:». Перегенерировать этот файл нужно, только если меняется сам формат
блоков — он коммитится в репозиторий, пересобирать при обычной работе не надо.
"""
from __future__ import annotations

import sys
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Font
from openpyxl.worksheet.worksheet import Worksheet

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parent.parent
OUT_PATH = ROOT / "seed" / "template.xlsx"

COLUMNS_HEADER = ["Ментор", "Номер телефона", "#", "Ученик", "Контакты", "Школа", "Класс"]
MARKER = "Настоящие группы отсюда:"

ROWS: list[list] = [
    ["ШАБЛОН — так устроена одна группа. Этот блок и блок «ПРИМЕР» ниже не "
     "импортируются, они только для наглядности. Название/смена/дата/формат "
     "могут стоять в любых из этих колонок — бот ищет по смыслу значения."],
    [],
    ["Группа А", "", "", "Утренняя", "27 июля", "Оффлайн"],
    COLUMNS_HEADER,
    ["Айгерим Смагулова", "+7 700 000 00 01", 1, "Иванов Иван Иванович",
     "+7 700 000 00 02", "НИШ IB", 9],
    ["", "", 2, "Петрова Мария Сергеевна", "+7 700 000 00 03", "БИЛ", 8],
    [],
    ["ПРИМЕР — с настоящими данными вида, реально присланного заказчиком "
     "(включая то, что телефон ментора протягивается вниз только визуально, "
     "а в ячейках он стоит один раз — в первой строке блока)."],
    [],
    ["Группа 1", "", "", "Утренняя", "27 июля", "Оффлайн"],
    COLUMNS_HEADER,
    ["Ерлан Тестов", "+7 700 111 71 13", 1, "Тестов Арман Серикулы",
     "+7 700 111 0070", "НИШ IB", 8],
    ["", "", 2, "Примеров Амир", "+7 700 111 7957", "РФМША", 7],
    ["", "", 3, "Образцова Айлин Маратовна", "+7 700 111 3033", "BINOM", 9],
    ["", "", 4, "Демо Ерсұлтан Қанатұлы", "+7 700 111 5177", "БИЛ", 9],
    ["", "", 5, "Мадина", "+7 700 111 3033", "БИЛ", 8],
    ["", "", 6, "Нуржан", "+7 700 111 0340", "БИЛ", 7],
    ["", "", 7, "Султан", "+7 700 111 7725", "БИЛ", 9],
    [],
    [MARKER],
    [],
    # Пустой блок — сюда вносить настоящие группы. Скопируй строку-заголовок
    # колонок и добавляй группы блоками так же, как в «ПРИМЕР» выше.
    ["Группа 1", "", "", "Утренняя", "", "Онлайн"],
    COLUMNS_HEADER,
]

BOLD_ROWS = {4, 11, 23}      # 1-based номера строк-заголовков колонок (после append)
BANNER_ROWS = {1, 8}         # 1-based номера строк с пояснительным текстом
MARKER_ROW = 20              # 1-based номер строки с маркером


def _fill_sheet(ws: Worksheet, rows: list[list]) -> None:
    for row in rows:
        ws.append(row)
    for r in BOLD_ROWS:
        for cell in ws[r]:
            cell.font = Font(bold=True)
    for r in BANNER_ROWS:
        ws.cell(row=r, column=1).font = Font(italic=True, color="666666")
    ws.cell(row=MARKER_ROW, column=1).font = Font(bold=True, color="C00000")

    widths: dict[int, int] = {}
    for row in rows:
        for i, value in enumerate(row, start=1):
            widths[i] = max(widths.get(i, 0), len(str(value)))
    for i, width in widths.items():
        ws.column_dimensions[ws.cell(row=1, column=i).column_letter].width = min(width + 4, 60)


def main() -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "Ростер"
    _fill_sheet(ws, ROWS)

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    wb.save(OUT_PATH)
    print(f"Готово: {OUT_PATH} ({OUT_PATH.stat().st_size} байт)")


if __name__ == "__main__":
    main()
